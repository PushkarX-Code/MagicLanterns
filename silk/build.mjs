// Writes silk.css from the tokens in silk.js, so CSS transitions move exactly like the GSAP moves.
// Each ease is sampled into a CSS linear() curve (springs and overshoots included). Run: node silk/build.mjs
import { writeFileSync } from 'node:fs'
import { gsap } from 'gsap'
import * as silk from './silk.js'

const curve = (name) => {
  const f = gsap.parseEase(name)
  const n = /elastic|back/.test(name) ? 48 : 24
  return `linear(${Array.from({ length: n + 1 }, (_, i) => +f(i / n).toFixed(4)).join(', ')})`
}
const kebab = (k) => k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())
const vars = [
  ...Object.entries(silk.EASE).map(([k, v]) => `  --silk-ease-${kebab(k)}: ${v === 'none' ? 'linear' : curve(v)}; /* ${v} */`),
  ...Object.entries(silk.DUR).map(([k, v]) => `  --silk-dur-${kebab(k)}: ${Math.round(v * 1000)}ms;`),
  ...Object.entries(silk.STAGGER).map(([k, v]) => `  --silk-stagger-${kebab(k)}: ${Math.round(v * 1000)}ms;`),
]
const css = `/* Silk ${silk.VERSION}: generated by silk/build.mjs from silk/silk.js. Do not edit by hand. */
:root {
${vars.join('\n')}
}

/* Press: driven by --press from silk.initPress(); uses the independent scale property so it stacks on lifts. */
button,
[data-press] {
  scale: var(--press, 1);
}

/* Motion blur from scroll speed: silk.motionBlur() writes --mb and --ms. */
.silk-mb {
  filter: blur(var(--mb, 0px));
  scale: 1 var(--ms, 1);
}

/* CSS-only moves for places without JS. */
.silk-lift {
  transition:
    transform var(--silk-dur-focus) var(--silk-ease-lift),
    opacity var(--silk-dur-focus) var(--silk-ease-lift);
}
.silk-lift:hover,
.silk-lift:focus-visible {
  transform: translateY(-${silk.LIFT.rise}px) scale(${silk.LIFT.scale});
}
.silk-fade {
  transition: opacity var(--silk-dur-fade) var(--silk-ease-glide);
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --silk-dur-settle: 200ms;
    --silk-dur-reveal: 200ms;
    --silk-dur-title: 200ms;
    --silk-dur-flight: 200ms;
    --silk-dur-draw: 200ms;
  }
  .silk-lift:hover,
  .silk-lift:focus-visible {
    transform: none;
  }
  .silk-mb {
    filter: none;
    scale: 1;
  }
}
`
writeFileSync(new URL('./silk.css', import.meta.url), css)
console.log('silk.css written for Silk', silk.VERSION)
